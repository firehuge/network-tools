/* Headless browser test for the Decommission tab in pan-flowmapper.html (system Chrome + playwright-core). Synthetic sample only. */
import { chromium } from "playwright-core";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { startStaticServer, isLocalTestUrl } from "./static-server.mjs";
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const srv = await startStaticServer(ROOT);
const chrome = process.env.CHROME_PATH || ["/usr/bin/google-chrome-stable", "/usr/bin/google-chrome", "/usr/bin/chromium"].find((p) => fs.existsSync(p));
let failed = 0;
const ok = (c, m) => { if (c) console.log("  ok  :", m); else { failed++; console.error("  FAIL:", m); } };
const browser = await chromium.launch({ executablePath: chrome, args: ["--no-sandbox", "--disable-dev-shm-usage"], headless: true });
const page = await (await browser.newContext({ viewport: { width: 1500, height: 1000 }, acceptDownloads: true })).newPage();
const errors = [], requests = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("request", (r) => { if (!isLocalTestUrl(r.url(), srv.port)) requests.push(r.url()); });
await page.goto(srv.url("/pan-flowmapper.html"));
await page.waitForFunction(() => window.__FM && window.__FM.ready);
console.log("\n== Decommission tab ==");
await page.locator("#fi").setInputFiles([path.join(ROOT, "samples", "panorama-decom-messy.xml")]);
await page.waitForFunction(() => window.__FM.ready === true && window.__FM.state.files.length === 1, null, { timeout: 60000 });
await page.locator('#tabs button[data-tab="decom"]').click();
ok(await page.locator("#tab-decom").isVisible(), "tab opens");
await page.fill("#dc-items", "10.50.1.25");
await page.locator('#dc-form button[type="submit"]').click();
await page.waitForSelector("#dc-out .dc-sum");
const sum = await page.locator("#dc-out .dc-sum").innerText();
ok(/4 exact/.test(sum) && /5 highly likely/.test(sum) && /5 possible/.test(sum), "tier counts shown: " + sum.split("·")[0].trim());
ok(await page.locator("#dc-out input[data-id]:checked").count() === 4, "only exact items are ticked");
ok(await page.locator("#dc-out .dc-danger li").count() === 3, "dangers listed");
const before = await page.locator("#dc-out table.data").last().locator("tbody tr").count();
await page.locator('#dc-out input[data-id^="rule|"]').first().check();
await page.waitForFunction((n) => document.querySelectorAll("#dc-out input[data-id]:checked").length === 5, null, { timeout: 5000 });
ok(/5 selected/.test(await page.locator("#dc-out .dc-sum").innerText()), "ticking a highly likely item rebuilds the plan");
await page.check('input[name="dc-mode"][value="block"]');
ok(await page.locator("#dc-flows").isVisible(), "stop traffic shows the flows box");
await page.fill("#dc-flows", "10.1.1.10 10.50.1.25 tcp/443");
await page.locator('#dc-form button[type="submit"]').click();
await page.waitForSelector("#dc-out .dc-fix");
ok(await page.locator("#dc-out .dc-fix").count() === 2, "a deny rule for each place");
ok(/R-APPS-BROAD/.test(await page.locator("#dc-out").innerText()), "redundant permit named");
const [dl] = await Promise.all([page.waitForEvent("download"), page.locator("#dc-csv").click()]);
ok(/decommission-plan\.csv/.test(dl.suggestedFilename()), "CSV export downloads");
ok(errors.length === 0, "no page errors" + (errors.length ? ": " + errors.join(" | ") : ""));
ok(requests.length === 0, "no network requests");
await browser.close();
await srv.close();
console.log(failed ? "\n" + failed + " failed" : "\nall passed");
process.exit(failed ? 1 : 0);
